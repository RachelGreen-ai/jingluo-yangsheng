#!/usr/bin/env python3
# Correction pass: nudge any acupoint that fell on the white background onto the
# nearest on-body pixel of the CC0 photo. Keeps points on skin without hand-tuning each.
import os,sys,runpy,math
from PIL import Image
HERE=os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE,'data','geom'))
IMG={'front':Image.open('/tmp/front_view.jpg').convert('RGB'),
     'back':Image.open(os.path.join(HERE,'..','assets','back.jpg')).convert('RGB')}

def onbody(im,x,y):
    W,H=im.size
    px=min(W-1,max(0,int(round(x/100*W)))); py=min(H-1,max(0,int(round(y/150*H))))
    r,g,b=im.getpixel((px,py))
    return (255-r)+(255-g)+(255-b) > 35

def snap(im,x,y,maxr=16.0):
    if onbody(im,x,y): return x,y,False
    best=None;bd=1e9
    r=0.4
    while r<=maxr:
        steps=max(8,int(r*8))
        for s in range(steps):
            a=2*math.pi*s/steps
            nx=x+r*math.cos(a); ny=y+r*math.sin(a)
            if 0<=nx<=100 and 0<=ny<=150 and onbody(im,nx,ny):
                d=r
                if d<bd: bd=d;best=(round(nx,2),round(ny,2))
        if best: return best[0],best[1],True
        r+=0.3
    return x,y,False

keys=sys.argv[1:] or ['li','sj','st','sp','ht','si','bl','ki','pc','gb','lr']
for k in keys:
    path=os.path.join(HERE,'data','geom',k+'.py')
    G=runpy.run_path(path)['G']; im=IMG[G['img']]
    moved=0;fail=[]
    for code,c in G['coords'].items():
        if c.get('x') is None or not c.get('onMain',True): continue
        nx,ny,ch=snap(im,c['x'],c['y'])
        if ch: c['x'],c['y']=nx,ny; moved+=1
        elif not onbody(im,c['x'],c['y']): fail.append(code)
    with open(path,'w',encoding='utf-8') as f:
        f.write('# auto-generated by gen_geom.py + snap_geom.py — coords on CC0 photo\n')
        f.write('G='+repr(G)+'\n')
    print('%-4s snapped %2d %s'%(k,moved,('' if not fail else 'STILL-OFF:'+','.join(fail))))
